/* Builds js/rpt1-experience.js, the context-row store for rpt1-v2.

   Self-play with the El-Tetris heuristic: a third of the games play it
   straight, the rest make 15 % or 40 % random moves so the store also holds
   high, messy stacks. For each move, six candidates spread across the
   heuristic's ranking (best, worst and evenly in between) become rows,
   labelled with their El-Tetris score -- good and bad moves, not only the
   ones that were played.

     node tools/build-rpt1-experience.mjs

   Deterministic: the same seed always writes the same file.

   Tried and dropped: labelling rows with what happened over the next few
   pieces instead of the heuristic score. Beyond the 3 preview pieces that
   label is mostly the luck of the draw, and the heuristic already clears
   ~97 % of the lines that are physically possible, so there is little left
   for it to find. See "Feeding RPT-1 better data" in the README. */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..') + '/';
const GAMES = 24;
const MAX_PIECES = 110;
const PER_MOVE = 6;
const EPSILONS = [0, 0.15, 0.4];

const win = { location: { protocol: 'file:' } };
for (const f of ['js/tetris.js', 'js/features.js', 'js/pickers.js', 'js/picker-rpt1-v2.js'])
  new Function('window', 'location', fs.readFileSync(ROOT + f, 'utf8'))(win, win.location);
const { Tetris: T, Features: F, Rpt1V2 } = win;

const rand = T.mulberry32(20261021);

function pieceStream(n) {
  const out = [];
  let bag = [];
  while (out.length < n) {
    if (!bag.length) {
      bag = T.TYPES.slice();
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(rand() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    out.push(bag.pop());
  }
  return out;
}

const rows = [];
for (let g = 0; g < GAMES; g++) {
  const eps = EPSILONS[g % EPSILONS.length];
  const pieces = pieceStream(MAX_PIECES + 1);
  let grid = T.emptyGrid(T.ROWS, T.COLS);
  for (let i = 0; i < MAX_PIECES; i++) {
    const cands = F.enumeratePlacements(grid, pieces[i]);
    if (!cands.length) break;
    const sorted = cands.slice().sort((a, b) => F.scorePlacement(b) - F.scorePlacement(a));
    const stack = F.boardFeatures(grid).maxHeight;
    const picks = new Set();
    for (let k = 0; k < PER_MOVE; k++) {
      picks.add(sorted[Math.round((k / (PER_MOVE - 1)) * (sorted.length - 1))]);
    }
    for (const p of picks) {
      rows.push([stack, Math.round(F.scorePlacement(p) * 100) / 100,
        ...Rpt1V2.featureValues(grid, p, pieces[i + 1])]);
    }
    const played = rand() < eps ? cands[Math.floor(rand() * cands.length)] : sorted[0];
    grid = played.nextGrid;
  }
  process.stderr.write(`game ${g + 1}/${GAMES} (eps ${eps}) -> ${rows.length} rows\n`);
}

const out = '/* Generated by tools/build-rpt1-experience.mjs -- do not edit.\n'
  + `   ${rows.length} rows from ${GAMES} self-play games; row = [stack_height_before,\n`
  + '   el_tetris_score, ...Rpt1V2.COLUMNS]. */\n'
  + 'window.RPT1_EXPERIENCE = ' + JSON.stringify({ columns: Rpt1V2.COLUMNS, rows })
    .replace(/\],\[/g, '],\n[') + ';\n';
fs.writeFileSync(ROOT + 'js/rpt1-experience.js', out);
console.log(`wrote js/rpt1-experience.js: ${rows.length} rows, ${(out.length / 1024).toFixed(0)} KB`);
